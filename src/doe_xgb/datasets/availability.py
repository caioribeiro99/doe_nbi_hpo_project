"""Dataset availability checks.

Performs a lightweight reachability probe (HTTP HEAD) on each canonical
URL. Network failures are reported as ``unavailable`` with a reason
string; they do not raise. ``sklearn``-backed datasets always report
``available`` because they ship inside the package.
"""

from __future__ import annotations

import json
import urllib.error
import urllib.request
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Literal

from .metadata import DatasetMetadata
from .registry import REGISTRY, list_dataset_ids

Status = Literal["available", "unavailable", "ambiguous", "manual_review"]


@dataclass(frozen=True)
class AvailabilityResult:
    dataset_id: str
    display_name: str
    status: Status
    canonical_url: str | None
    openml_id: int | None
    http_status: int | None = None
    reason: str | None = None
    notes: list[str] = field(default_factory=list)


def _probe_url(url: str, timeout: float = 5.0) -> tuple[bool, int | None, str | None]:
    req = urllib.request.Request(url, method="HEAD",
                                  headers={"User-Agent": "doe-xgb/0.2"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:  # noqa: S310
            return True, int(resp.status), None
    except urllib.error.HTTPError as e:
        # Some UCI mirrors reject HEAD; fall back to GET (range 0-0).
        try:
            req_get = urllib.request.Request(
                url,
                method="GET",
                headers={"User-Agent": "doe-xgb/0.2", "Range": "bytes=0-0"},
            )
            with urllib.request.urlopen(req_get, timeout=timeout) as resp:  # noqa: S310
                return True, int(resp.status), f"HEAD failed ({e.code}); GET succeeded."
        except Exception as ge:  # pragma: no cover - exotic network paths
            return False, e.code, f"HEAD {e.code}; GET also failed: {ge}"
    except (TimeoutError, urllib.error.URLError) as e:
        return False, None, f"network error: {e}"
    except Exception as e:  # pragma: no cover - defensive
        return False, None, f"unexpected error: {e}"


def check_dataset(meta: DatasetMetadata, *, timeout: float = 5.0) -> AvailabilityResult:
    notes: list[str] = []
    if meta.notes:
        notes.append(meta.notes)
    if meta.source_type == "sklearn":
        return AvailabilityResult(
            dataset_id=meta.dataset_id,
            display_name=meta.display_name,
            status="available",
            canonical_url=None,
            openml_id=None,
            reason="bundled with scikit-learn",
            notes=notes,
        )
    if meta.source_type == "uci" and meta.source_url:
        ok, status, reason = _probe_url(meta.source_url, timeout=timeout)
        return AvailabilityResult(
            dataset_id=meta.dataset_id,
            display_name=meta.display_name,
            status="available" if ok else "unavailable",
            canonical_url=meta.source_url,
            openml_id=meta.openml_id,
            http_status=status,
            reason=reason,
            notes=notes,
        )
    if meta.source_type == "openml" and meta.openml_id is not None:
        url = f"https://www.openml.org/d/{int(meta.openml_id)}"
        ok, status, reason = _probe_url(url, timeout=timeout)
        return AvailabilityResult(
            dataset_id=meta.dataset_id,
            display_name=meta.display_name,
            status="available" if ok else "unavailable",
            canonical_url=url,
            openml_id=meta.openml_id,
            http_status=status,
            reason=reason,
            notes=notes,
        )
    return AvailabilityResult(
        dataset_id=meta.dataset_id,
        display_name=meta.display_name,
        status="manual_review",
        canonical_url=meta.source_url,
        openml_id=meta.openml_id,
        reason="no canonical URL or OpenML id; manual review required",
        notes=notes,
    )


def check_all(*, timeout: float = 5.0) -> list[AvailabilityResult]:
    return [check_dataset(REGISTRY[i], timeout=timeout) for i in list_dataset_ids()]


def write_availability_report(
    results: list[AvailabilityResult],
    *,
    out_md: Path,
    out_json: Path,
) -> None:
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(
        json.dumps([asdict(r) for r in results], indent=2),
        encoding="utf-8",
    )

    lines: list[str] = []
    lines.append("# Dataset availability report\n")
    lines.append(
        "Auto-generated by `doe-xgb datasets check-availability`. "
        "HEAD/GET probe with a 5s timeout; sklearn-backed datasets are "
        "always available.\n"
    )
    lines.append(
        "| ID | Name | Status | HTTP | OpenML | Reason / notes |\n"
        "|---|---|---|---:|---:|---|\n"
    )
    for r in results:
        notes = " ".join(r.notes or [])
        reason = r.reason or ""
        merged = "; ".join(s for s in (reason, notes) if s)
        lines.append(
            f"| `{r.dataset_id}` | {r.display_name} | {r.status} | "
            f"{r.http_status if r.http_status is not None else ''} | "
            f"{r.openml_id if r.openml_id is not None else ''} | {merged} |\n"
        )
    out_md.write_text("".join(lines), encoding="utf-8")


__all__ = [
    "AvailabilityResult",
    "Status",
    "check_dataset",
    "check_all",
    "write_availability_report",
]
