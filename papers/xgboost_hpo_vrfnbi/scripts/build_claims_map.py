#!/usr/bin/env python
"""Generate CONFIRMATORY_CLAIMS_AND_EVIDENCE.md from the verified artifacts.

This document is the ONLY permitted source for headline numerical claims in the
manuscript. Every figure in it is read from a committed artifact at generation time,
so a claim cannot drift from its evidence: regenerate and the document changes, or
the check fails.
"""
from __future__ import annotations

