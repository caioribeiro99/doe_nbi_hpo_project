import re
import shutil
import subprocess
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
MAN = PAPER / "manuscript"
SRC = MAN / "MANUSCRIPT.md"
OUT = MAN / "latex"
FIG = MAN / "figures"

