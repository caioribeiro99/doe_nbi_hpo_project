#!/usr/bin/env python
"""Convert the assembled manuscript into an Elsevier ``elsarticle`` LaTeX source (decision C4).

Applied Soft Computing asks for editable source files ("A PDF is not an acceptable source
file"). This script reads ``manuscript/MANUSCRIPT.md``, which ``assemble_manuscript.py``
generates from ``manuscript/sections/*.md``, and writes:

    manuscript/latex/manuscript.tex        the main document (elsarticle, single column)
    manuscript/latex/figure_captions.tex   the figure captions as a separate file

The figures are the vector files ``manuscript/figures/Figure_1.pdf`` to ``Figure_6.pdf``
written by ``build_figures.py``. Mathematics is already TeX in the sections and is passed
through unmodified; nothing is transliterated to Unicode. The section numbers that the
text cites ("Section 5.14") are printed by LaTeX's own counters, so the converter checks
that every numbered heading agrees with the counter it will receive and stops otherwise.
Author metadata is the author-confirmed content of ``submission/ASOC_TITLE_PAGE.md``; the ORCID
iDs stay on the title page.

Usage:  python scripts/build_latex.py [--compile]
"""
