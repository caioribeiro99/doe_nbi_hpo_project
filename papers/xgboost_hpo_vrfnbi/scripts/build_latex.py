UNICODE_TEXT = {  # characters outside math that Latin Modern lacks or that LaTeX spells differently
    "\u2212": r"\textminus{}", "\u2192": r"$\rightarrow$", "\u207a": r"\textsuperscript{+}",
    "\u00a7": r"\S{}", "\u00b7": r"$\cdot$", "\u00d7": r"$\times$", "\u2265": r"$\geq$",
    "\u2264": r"$\leq$", "\u2248": r"$\approx$", "\u00b1": r"$\pm$", "\u2014": "---", "\u2013": "--",
}


def escape_text(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\": out.append(r"\textbackslash{}")
        elif ch in "&%#_{}$": out.append("\\" + ch)
        elif ch == "~": out.append(r"\textasciitilde{}")
        elif ch == "^": out.append(r"\textasciicircum{}")
        else: out.append(UNICODE_TEXT.get(ch, ch))
    return "".join(out)


def tt(s: str) -> str:
    """Inline code: monospace, escaped, breakable after path separators."""
    e = escape_text(s)
    return r"\texttt{" + re.sub(r"(/|\\_|\.|-)", r"\1\\allowbreak{}", e) + "}"


def inline(s: str) -> str:
    """Render one paragraph of inline Markdown (math, code, links, emphasis) to LaTeX."""
    slots: list[str] = []

    def keep(x: str) -> str:
        slots.append(x)
        return f"\x00{len(slots) - 1}\x00"

    s = re.sub(r"(?<!\\)\$\$(.+?)\$\$", lambda m: keep(r"\[" + m.group(1) + r"\]"), s, flags=re.S)
    s = re.sub(r"(?<![\\$])\$(?!\$)(.+?)(?<!\\)\$", lambda m: keep("$" + m.group(1) + "$"), s)
    s = re.sub(r"`([^`]+)`", lambda m: keep(tt(m.group(1))), s)
    s = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)",
               lambda m: keep(r"\href{" + m.group(2) + "}{" + inline(m.group(1)) + "}"), s)
    s = re.sub(r"https?://[^\s)<>]+[^\s)<>.,;:]", lambda m: keep(r"\url{" + m.group(0) + "}"), s)
    s = escape_text(s)
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
    s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\\emph{\1}", s)
    s = s.replace("\u201c", "``").replace("\u201d", "''")
    while "\x00" in s:
        s = re.sub(r"\x00(\d+)\x00", lambda m: slots[int(m.group(1))], s)
    return s


def parse_blocks(lines: list[str]) -> list[tuple]:
    blocks, i = [], 0
    while i < len(lines):
        ln = lines[i]
        if not ln.strip():
            i += 1; continue
        m = re.match(r"^(#{1,4})\s+(.*)$", ln)
        if m:
            blocks.append(("h", len(m.group(1)), m.group(2).strip())); i += 1; continue
        if ln.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(lines[i]); i += 1
            blocks.append(("table", rows)); continue
        if ln.strip().startswith("$$"):
            buf = [ln]
            while not buf[-1].rstrip().endswith("$$") or (len(buf) == 1 and buf[0].strip() == "$$"):
                i += 1; buf.append(lines[i])
            i += 1
            blocks.append(("math", "\n".join(buf).strip()[2:-2].strip())); continue
        if re.match(r"^\s*([-*]|\d+\.)\s+", ln):
            items, ordered = [], bool(re.match(r"^\s*\d+\.", ln))
            while i < len(lines) and lines[i].strip():
                if re.match(r"^\s*([-*]|\d+\.)\s+", lines[i]):
                    items.append(re.sub(r"^\s*([-*]|\d+\.)\s+", "", lines[i]))
                else:
                    items[-1] += " " + lines[i].strip()
                i += 1
            blocks.append(("list", ordered, items)); continue
        buf = []
        while i < len(lines) and lines[i].strip() and not lines[i].startswith(("|", "#")) \
                and not lines[i].strip().startswith("$$"):
            buf.append(lines[i].strip()); i += 1
        blocks.append(("p", " ".join(buf)))
    return blocks


def table_tex(rows: list[str], caption: str, number: int) -> str:
    """Pipe table -> booktabs table, caption above. Text-heavy tables wrap in tabularx;
    numeric tables keep their natural width and are scaled down only if they exceed the
    text width (adjustbox max width), so no table runs into the margin."""
    cells = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows]
    head, sep, body = cells[0], cells[1], cells[2:]
    ncol = len(head)
    aligns = []
    for c in sep:
        c = c.replace(" ", "")
        aligns.append("r" if c.endswith(":") and not c.startswith(":") else
                      "c" if c.startswith(":") and c.endswith(":") else "l")
    width = [max(len(re.sub(r"[`*$\\{}]", "", r[j])) for r in [head] + body) for j in range(ncol)]
    text_heavy = any(width[j] > 40 and aligns[j] == "l" for j in range(ncol))
    if text_heavy:
        spec = ["Y" if width[j] > 18 and aligns[j] == "l" else aligns[j] for j in range(ncol)]
        open_env, close_env = r"\begin{tabularx}{\textwidth}{" + "".join(spec) + "}", r"\end{tabularx}"
    else:
        open_env = r"\begin{adjustbox}{max width=\textwidth}" + "\n" + r"\begin{tabular}{" + "".join(aligns) + "}"
        close_env = r"\end{tabular}" + "\n" + r"\end{adjustbox}"
    out = [rf"\setcounter{{table}}{{{number - 1}}}", r"\begin{table}[htbp]", r"\centering", r"\footnotesize",
           r"\caption{" + caption + "}", rf"\label{{tab:{number}}}", open_env, r"\toprule",
           " & ".join(r"\textbf{" + inline(h) + "}" if h else "" for h in head) + r" \\", r"\midrule"]
    for r in body:
        r = (r + [""] * ncol)[:ncol]
        out.append(" & ".join(inline(c) for c in r) + r" \\")
    out += [r"\bottomrule", close_env, r"\end{table}"]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--compile", action="store_true", help="compile with tectonic into manuscript/latex/")
    args = ap.parse_args()
    lines = SRC.read_text(encoding="utf-8").split("\n")
    blocks = parse_blocks(lines)

    title = next(b[2] for b in blocks if b[0] == "h" and b[1] == 1)
    # Split off the figure captions; they become floats and a separate captions file.
    fig_caps: dict[int, str] = {}
    body, in_caps = [], False
    for b in blocks:
        if b[0] == "h" and b[1] == 2:
            in_caps = b[2].lower() == "figure captions"
            if in_caps: continue
        if in_caps:
            if b[0] == "p":
                m = re.match(r"\*\*Figure (\d+)\.\s*(.+?)\*\*\s*(.*)$", b[1])
                if not m:
                    raise SystemExit(f"unparsed caption paragraph: {b[1][:80]}")
                fig_caps[int(m.group(1))] = r"\textbf{" + inline(m.group(2)) + "} " + inline(m.group(3))
            continue
        body.append(b)

    # Pair each table with its "**Table N.**" caption paragraph (immediately before or after it).
    tex, abstract, keywords = [], [], []
    counters = [0, 0, 0]
    tables_seen = 0
    used = set()
    figs_placed: set[int] = set()
    mode = "front"
    k = 0
    while k < len(body):
        b = body[k]
        if b[0] == "h":
            level, text = b[1], b[2]
            if level == 1:
                k += 1; continue
            if level == 2 and text.lower() == "abstract":
                mode = "abstract"; k += 1; continue
            mode = "body"
            m = re.match(r"^(\d+(?:\.\d+)*)\.?\s+(.*)$", text)
            if m and level >= 2:
                nums = [int(x) for x in m.group(1).split(".")]
                lvl = level - 2
                counters[lvl] += 1
                for j in range(lvl + 1, 3): counters[j] = 0
                expect = counters[:lvl + 1]
                if nums != expect:
                    raise SystemExit(f"heading number {m.group(1)} does not match LaTeX counter {expect}: {text}")
                cmd = ["section", "subsection", "subsubsection"][lvl]
                tex.append(f"\\{cmd}{{{inline(m.group(2))}}}\\label{{sec:{m.group(1)}}}")
            else:
                cmd = ["section*", "subsection*", "subsubsection*"][level - 2]
                tex.append(f"\\{cmd}{{{inline(text)}}}")
                if level == 2 and text.lower() == "references":
                    mode = "refs"
            k += 1; continue
        if mode == "abstract":
            if b[0] == "p" and b[1].startswith("**Keywords:**"):
                keywords = [x.strip().rstrip(".") for x in b[1][len("**Keywords:**"):].split(";")]
            elif b[0] == "p":
                abstract.append(inline(b[1]))
            k += 1; continue
        if b[0] == "table":
            cap = None
            for nb in (k - 1, k + 1):
                if 0 <= nb < len(body) and body[nb][0] == "p" and re.match(r"\*\*Table \d+\.\*\*", body[nb][1]):
                    cap = nb; break
            if cap is None:
                raise SystemExit("table without an adjacent '**Table N.**' caption")
            tables_seen += 1
            n = int(re.match(r"\*\*Table (\d+)\.\*\*", body[cap][1]).group(1))
            if n != tables_seen:  # the journal numbers tables in order of appearance
                print(f"WARNING: Table {n} is placed in position {tables_seen}; its number is kept")
            capt = inline(re.sub(r"^\*\*Table \d+\.\*\*\s*", "", body[cap][1]))
            if cap == k - 1 and tex and tex[-1].startswith("%CAPTION"):
                tex.pop()
            used.add(cap)
            tex.append(table_tex(b[1], capt, n))
            k += 1; continue
        if b[0] == "p" and re.match(r"\*\*Table \d+\.\*\*", b[1]):
            nxt = body[k + 1] if k + 1 < len(body) else None
            if nxt and nxt[0] == "table":
                tex.append("%CAPTION")  # placeholder, removed when the table is emitted
            k += 1; continue
        if b[0] == "math":
            m_tag = re.search(r"\\tag\{(\d+)\}", b[1])
            if m_tag:  # numbered exactly as the text numbers it; the counter (not \tag) keeps anchors unique
                body_math = re.sub(r"\s*\\tag\{\d+\}", "", b[1])
                tex.append(f"\\setcounter{{equation}}{{{int(m_tag.group(1)) - 1}}}\n\\begin{{equation}}\n"
                           + body_math + "\n\\end{equation}")
            else:
                tex.append("\\begin{equation*}\n" + b[1] + "\n\\end{equation*}")
        elif b[0] == "list":
            env = "enumerate" if b[1] else "itemize"
            tex.append(f"\\begin{{{env}}}\n" + "\n".join(r"\item " + inline(x) for x in b[2]) + f"\n\\end{{{env}}}")
        elif b[0] == "p":
            if mode == "refs":
                tex.append(r"\noindent\hangindent=1.5em\hangafter=1 " + inline(b[1]) + r"\par\smallskip")
            else:
                tex.append(inline(b[1]))
                for n in sorted(fig_caps):
                    if n not in figs_placed and re.search(rf"\bFigure~?\s*{n}\b", b[1]):
                        figs_placed.add(n)
                        tex.append(figure_tex(n, fig_caps[n]))
        k += 1
    for n in sorted(set(fig_caps) - figs_placed):
        tex.append(figure_tex(n, fig_caps[n]))
    tex = [t for t in tex if t != "%CAPTION"]

    OUT.mkdir(parents=True, exist_ok=True)
    doc = [PREAMBLE, r"\begin{document}", r"\begin{frontmatter}",
           r"\title{" + inline(title) + r"\tnoteref{abbrev}}", r"\tnotetext[abbrev]{" + inline(ABBREVIATIONS) + "}",
           AUTHORS.strip(), r"\begin{abstract}", "\n\n".join(abstract), r"\end{abstract}",
           r"\begin{keyword}", " \\sep ".join(inline(x) for x in keywords), r"\end{keyword}",
           r"\end{frontmatter}", "", "\n\n".join(tex), "", r"\end{document}", ""]
    (OUT / "manuscript.tex").write_text("\n".join(doc), encoding="utf-8")
    caps = ["%% Figure captions, supplied as a separate file (Applied Soft Computing, figures section).",
            "%% Generated by scripts/build_latex.py from manuscript/sections/12_figure_captions.md.", ""]
    for n in sorted(fig_caps):
        caps.append(rf"\noindent\textbf{{Figure {n}.}} {fig_caps[n]}\par\medskip")
    (OUT / "figure_captions.tex").write_text("\n".join(caps) + "\n", encoding="utf-8")
    missing = [n for n in fig_caps if not (FIG / f"Figure_{n}.pdf").exists()]
    print(f"wrote {OUT / 'manuscript.tex'}: {len(tex)} blocks, {tables_seen} tables, {len(fig_caps)} figures"
          + (f"; MISSING vector figures {missing}" if missing else ""))
    print(f"abstract: {len(' '.join(abstract).split())} whitespace tokens; keywords {len(keywords)}")
    if args.compile:  # build in a temporary directory; only the PDF is kept beside the source
        import tempfile
        with tempfile.TemporaryDirectory() as tmp:
            r = subprocess.run(["tectonic", "-o", tmp, "manuscript.tex"], cwd=OUT, capture_output=True, text=True)
            warn = [ln for ln in r.stderr.splitlines() if "Overfull" in ln or "Undefined" in ln or "error" in ln]
            print(f"tectonic exit {r.returncode}; {len(warn)} overfull/undefined/error lines")
            for ln in warn[:20]:
                print("  " + ln)
            if r.returncode:
                sys.stdout.write(r.stderr[-3000:]); return r.returncode
            shutil.copy2(Path(tmp) / "manuscript.pdf", OUT / "manuscript.pdf")
    return 0


def figure_tex(n: int, caption: str) -> str:
    return "\n".join([r"\begin{figure}[htbp]", r"\centering",
                      rf"\includegraphics[width=\textwidth,height=0.42\textheight,keepaspectratio]{{Figure_{n}.pdf}}",
                      r"\caption{" + caption + "}", rf"\label{{fig:{n}}}", r"\end{figure}"])


if __name__ == "__main__":
    raise SystemExit(main())
